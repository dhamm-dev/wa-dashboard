import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { spawnSync } from 'node:child_process';

test('legacy schedules retain active times and ambiguous null times become inactive', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'wa-migration-'));
  const legacy = new DatabaseSync(join(dir, 'dashboard.sqlite'));
  legacy.exec(`CREATE TABLE schedules(id TEXT PRIMARY KEY, account_id TEXT NOT NULL, jid TEXT NOT NULL, text TEXT NOT NULL, attachment_id TEXT, repeat TEXT NOT NULL, next_at TEXT, created_at TEXT NOT NULL);
    CREATE TABLE accounts(id TEXT PRIMARY KEY, name TEXT NOT NULL);
    CREATE TABLE templates(id TEXT PRIMARY KEY, name TEXT NOT NULL, text TEXT NOT NULL);
    INSERT INTO accounts VALUES ('legacy', 'Akun lama');
    INSERT INTO templates VALUES ('legacy-template', 'Template lama', 'Pesan lama');
    INSERT INTO schedules VALUES ('a','account','62812345678@s.whatsapp.net','x',NULL,'weekly','2030-01-01T00:00:00.000Z','2026-01-01T00:00:00.000Z');
    INSERT INTO schedules VALUES ('b','account','62812345678@s.whatsapp.net','x',NULL,'once',NULL,'2026-01-01T00:00:00.000Z');`);
  legacy.close();
  process.env.DATA_DIR = dir;
  const { db } = await import('../src/db.js');
  assert.deepEqual({ ...db.prepare('SELECT email,role,google_sub FROM users WHERE id=?').get('legacy-admin') }, { email: 'idhamk654@gmail.com', role: 'admin', google_sub: null });
  assert.deepEqual({ ...db.prepare('SELECT name,owner_id,role FROM accounts WHERE id=?').get('legacy') }, { name: 'Akun lama', owner_id: 'legacy-admin', role: 'ordinary' });
  assert.deepEqual({ ...db.prepare('SELECT name,text,owner_id FROM templates WHERE id=?').get('legacy-template') }, { name: 'Template lama', text: 'Pesan lama', owner_id: 'legacy-admin' });
  db.prepare("INSERT INTO users VALUES ('customer','customer@example.test',NULL,'customer')").run();
  assert.throws(() => db.prepare("INSERT INTO accounts(id,name,owner_id,role) VALUES ('bot','Bot','customer','bot')").run(), /bot requires admin owner/);
  assert.throws(() => db.prepare("INSERT INTO accounts(id,name) VALUES ('no-owner','No owner')").run(), /owner required/);
  assert.deepEqual({ ...db.prepare('SELECT enabled,next_at,revision,last_at FROM schedules WHERE id=?').get('a') }, { enabled: 1, next_at: '2030-01-01T00:00:00.000Z', revision: 0, last_at: null });
  assert.deepEqual({ ...db.prepare('SELECT enabled,next_at,revision,last_at FROM schedules WHERE id=?').get('b') }, { enabled: 0, next_at: null, revision: 0, last_at: null });
  db.prepare("UPDATE accounts SET owner_id='customer' WHERE id='legacy'").run();
  db.close();
  const restart = spawnSync(process.execPath, ['--input-type=module', '-e', "const { db } = await import('./src/db.js'); if (db.prepare('SELECT owner_id FROM accounts WHERE id=?').get('legacy').owner_id !== 'customer') process.exit(2); db.close()"], { cwd: process.cwd(), env: { ...process.env, DATA_DIR: dir }, encoding: 'utf8' });
  assert.equal(restart.status, 0, restart.stderr);
  rmSync(dir, { recursive: true, force: true });
});
